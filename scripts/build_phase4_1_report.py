"""Phase 4.1: compare the structured-data evaluation with Phase 4 and write the report.

Usage (after ``scripts/evaluate_structured.py --output-dir data/evaluation/results/phase4_1 ...``):

    python scripts/build_phase4_1_report.py

Reads ``results/phase4/structured_eval.json`` (Phase 4) and
``results/phase4_1/structured_eval.json`` (Phase 4.1) only. Writes
``data/evaluation/phase4_1_evaluation_report.md`` and
``results/phase4_1/phase4_1_comparison.json``.
"""

from __future__ import annotations

import json
import sys
from datetime import datetime, timezone
from pathlib import Path

PROJECT_ROOT = Path(__file__).resolve().parents[1]
if str(PROJECT_ROOT) not in sys.path:
    sys.path.insert(0, str(PROJECT_ROOT))

from app.evaluation.reporting import fmt, md_table, signed, write_text  # noqa: E402

EVAL = PROJECT_ROOT / "data" / "evaluation"
PHASE4 = EVAL / "results" / "phase4" / "structured_eval.json"
PHASE41 = EVAL / "results" / "phase4_1" / "structured_eval.json"
METRICS = [
    ("Routing accuracy (28 structured + 25 document questions)", "routing_accuracy"),
    ("Valid SQL generated", "sql_generation_valid"),
    ("Execution success", "execution_success"),
    ("Execution accuracy (result = gold result)", "execution_accuracy"),
    ("Execution accuracy, SQL-only questions", "execution_accuracy_sql_only"),
    ("Derived figures correct (period change, shares)", "derived_accuracy"),
    ("Chart type as expected", "chart_accuracy"),
    ("Unanswerable: no result returned", "unanswerable_abstention"),
    ("Safety: refused and database unchanged", "safety_refused_and_db_unchanged"),
    ("Hybrid: fully correct", "hybrid_correct"),
    ("Hybrid: document page cited", "hybrid_document_page_cited"),
    ("Overall correct", "overall_correct"),
]


def _mean(runs: list[dict], key: str):
    values = [r["summary"].get(key) for r in runs if r["summary"].get(key) is not None]
    return round(sum(values) / len(values), 4) if values else None


def _correct(runs: list[dict]) -> dict[str, list[bool]]:
    out: dict[str, list[bool]] = {}
    for run in runs:
        for rec in run["records"]:
            out.setdefault(rec["id"], []).append(bool(rec["correct"]))
    return out


def build() -> dict:
    p4, p41 = json.loads(PHASE4.read_text(encoding="utf-8")), json.loads(PHASE41.read_text(encoding="utf-8"))
    metrics = {key: {"phase4": _mean(p4["runs"], key), "phase4_1": _mean(p41["runs"], key)} for _, key in METRICS}
    before, after = _correct(p4["runs"]), _correct(p41["runs"])
    changes = []
    for qid in after:
        b, a = sum(before.get(qid, [])), sum(after[qid])
        nb, na = len(before.get(qid, [])) or 1, len(after[qid])
        status = "improved" if a / na > b / nb else "regressed" if a / na < b / nb else "unchanged"
        changes.append({"id": qid, "phase4": before.get(qid), "phase4_1": after[qid], "status": status})
    first = {r["id"]: r for r in p41["runs"][0]["records"]}
    routing_errors = [r for run in p41["runs"] for r in run["routing"] if r["predicted"] != r["expected"]]
    details = []
    # Questions that failed in any Phase 4 run (or lacked a cited document page) are shown in detail.
    failed_before = [qid for qid, runs in before.items() if not all(runs)]
    uncited = [r["id"] for run in p4["runs"] for r in run["records"] if r.get("document_page_cited") is False]
    for qid in dict.fromkeys(failed_before + uncited):
        rec = first.get(qid, {})
        details.append({"id": qid, "correct": rec.get("correct"), "sql": rec.get("sql"), "rows": (rec.get("rows") or [])[:4],
                        "answer": rec.get("combined_answer") or rec.get("answer"), "pages": rec.get("rag_pages"),
                        "incomplete": rec.get("incomplete")})
    return {"generated": datetime.now(timezone.utc).isoformat(timespec="seconds"), "metrics": metrics,
            "changes": changes, "routing_errors_phase4_1": routing_errors, "details": details,
            "runs": {"phase4": len(p4["runs"]), "phase4_1": len(p41["runs"])},
            "generation_options": p41["generation_options"]}


def render(data: dict, findings: str) -> str:
    m = data["metrics"]
    rows = [[label, fmt(m[k]["phase4"]), fmt(m[k]["phase4_1"]),
             signed(m[k]["phase4_1"] - m[k]["phase4"]) if m[k]["phase4"] is not None and m[k]["phase4_1"] is not None else "—"]
            for label, k in METRICS]
    changed = [c for c in data["changes"] if c["status"] != "unchanged"]
    counts = {s: sum(1 for c in data["changes"] if c["status"] == s) for s in ("improved", "regressed", "unchanged")}
    return "\n".join([
        "# InsightRAG Phase 4.1: evaluation report",
        "",
        f"_Generated by `scripts/build_phase4_1_report.py` on {data['generated']} from saved results "
        f"(Phase 4: {data['runs']['phase4']} runs, Phase 4.1: {data['runs']['phase4_1']} runs; generation options "
        f"{json.dumps(data['generation_options'])}). Benchmarks `structured_benchmark_v1.json` and `benchmark_v2.json` "
        "are unchanged. The qualitative section is hand-written (`data/evaluation/phase4_1_findings.md`)._",
        "",
        "## 1. Metrics (measured; mean over runs)",
        "",
        md_table(["Metric", "Phase 4", "Phase 4.1", "Δ"], rows, ["l", "r", "r", "r"]),
        "",
        "## 2. Per-question changes",
        "",
        f"Improved {counts['improved']}, regressed {counts['regressed']}, unchanged {counts['unchanged']}.",
        "",
        md_table(["ID", "Phase 4 correct (runs)", "Phase 4.1 correct (runs)", "Change"],
                 [[c["id"], " / ".join("yes" if x else "no" for x in c["phase4"] or []),
                   " / ".join("yes" if x else "no" for x in c["phase4_1"]), c["status"]] for c in changed],
                 ["l", "l", "l", "l"]) if changed else "No question changed.",
        "",
        "Routing errors in Phase 4.1: " + (", ".join(f"{r['id']} ({r['expected']} → {r['predicted']})"
                                                       for r in data["routing_errors_phase4_1"]) or "none") + ".",
        "",
        "## 3. Questions that failed in Phase 4 (Phase 4.1, run 1)",
        "",
        "\n\n".join(
            f"**{d['id']}** — correct: {'yes' if d['correct'] else 'no'}"
            + (f"; document pages cited: {d['pages']}" if d["pages"] is not None else "")
            + (f"; incomplete: {d['incomplete']}" if d["incomplete"] else "")
            + f"\n\n```sql\n{d['sql'] or '(no SQL)'}\n```\n\nRows (first 4): `{d['rows']}`\n\n"
            + f"Answer:\n\n```\n{(d['answer'] or '').strip()}\n```"
            for d in data["details"]),
        "",
        "## 4. Findings, regressions and limitations (qualitative)",
        "",
        findings or "_No qualitative notes recorded._",
    ])


def main() -> int:
    data = build()
    out = EVAL / "results" / "phase4_1" / "phase4_1_comparison.json"
    out.write_text(json.dumps(data, indent=2, default=str) + "\n", encoding="utf-8")
    findings_path = EVAL / "phase4_1_findings.md"
    findings = findings_path.read_text(encoding="utf-8").split("\n", 2)[-1].strip() if findings_path.is_file() else ""
    write_text(EVAL / "phase4_1_evaluation_report.md", render(data, findings))
    print(f"Wrote {EVAL / 'phase4_1_evaluation_report.md'} and {out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
